import { z } from "zod";

const record = z.record(z.string(), z.unknown());
const citation = z.looseObject({
  url: z.string().url(),
  version: z.string(),
  sectionUrl: z.string().url().nullable(),
  linkStatus: z.enum(["verified", "unverified"]),
  anchorCheckedAt: z.string().nullable(),
  excerptSha256: z.string().regex(/^[a-f0-9]{64}$/),
});
const source = z.enum(["help", "sales"]);
const sourceHealth = z.looseObject({
  source,
  version: z.string(),
  cached: z.number(),
  stale: z.number(),
  complete: z.boolean(),
});
const health = z.looseObject({
  scope: z.string(),
  guidance: z.string(),
  sources: z.array(sourceHealth),
  links: z.looseObject({
    pagesWithVerifiedAnchors: z.number(),
    pagesAwaitingCheck: z.number(),
    lastCheck: record.nullable(),
  }),
});

export const outputSchemas = {
  list_docs: z.looseObject({
    revision: z.string(),
    total: z.number(),
    offset: z.number(),
    nextOffset: z.number().nullable(),
    documents: z.array(
      z.looseObject({
        id: z.string(),
        source,
        title: z.string(),
        url: z.string().url(),
        version: z.string(),
        fetchedAt: z.string(),
        sha256: z.string(),
        totalLines: z.number(),
      }),
    ),
    coverage: record,
  }),
  search_docs: z.looseObject({
    revision: z.string(),
    results: z.array(
      citation.extend({
        id: z.string(),
        title: z.string(),
        source,
        sectionId: z.string(),
        headingPath: z.array(z.string()),
        startLine: z.number(),
        endLine: z.number(),
        fetchedAt: z.string(),
        sha256: z.string(),
        stale: z.boolean(),
        excerpt: z.string(),
        contentWarnings: z.array(z.string()),
      }),
    ),
    resultsTruncated: z.boolean(),
    guidance: z.string(),
    coverage: z.array(record),
    runtime: record,
  }),
  read_doc: citation.extend({
    id: z.string(),
    source,
    title: z.string(),
    revision: z.string(),
    fetchedAt: z.string(),
    sha256: z.string(),
    stale: z.boolean(),
    text: z.string(),
    startLine: z.number(),
    endLine: z.number(),
    totalLines: z.number(),
    nextLine: z.number().nullable(),
    section: record.nullable(),
    sections: z.array(record),
    sectionOffset: z.number(),
    totalSections: z.number(),
    nextSectionOffset: z.number().nullable(),
  }),
  docs_status: health.extend({
    server: z.object({ name: z.string(), version: z.string() }),
    connection: record,
    readiness: z.looseObject({
      state: z.enum([
        "preparing",
        "updating",
        "unavailable",
        "degraded",
        "ready",
      ]),
      usable: z.boolean(),
      message: z.string(),
      nextAction: z.string(),
    }),
    observability: record,
    runtime: record,
  }),
  refresh_docs: health,
  get_guidance: z.looseObject({
    revision: z.string(),
    question: z.string(),
    status: z.enum([
      "unsupported",
      "no_match",
      "needs_review",
      "stale",
      "ready",
    ]),
    topics: z.array(z.object({ id: z.string(), title: z.string() })),
    documentation: z.array(
      citation.extend({
        documentId: z.string(),
        source,
        sha256: z.string(),
        stale: z.boolean(),
        text: z.string(),
        sectionId: z.string(),
        startLine: z.number(),
        endLine: z.number(),
        nextLine: z.number().nullable(),
      }),
    ),
    recommendations: z.array(
      z.looseObject({
        id: z.string(),
        prerequisites: z.array(z.string()),
        steps: z.array(z.string()),
        verify: z.array(z.string()),
        sourceIds: z.array(z.string()),
        reviewRequired: z.boolean(),
        sourceReview: z.array(record),
      }),
    ),
    missingInformation: z.array(z.string()),
    warnings: z.array(z.string()),
    guideReviewedAt: z.string(),
    instruction: z.string(),
  }),
  capture_evidence: z.looseObject({
    status: z.enum([
      "captured",
      "source_changed",
      "ambiguous",
      "too_large",
      "unavailable",
      "busy",
    ]),
    documentId: z.string(),
    url: z.string().url(),
    sectionUrl: z.string().url().nullable(),
    linkStatus: z.enum(["verified", "unverified"]),
    revision: z.string(),
    sourceSha256: z.string(),
    excerptSha256: z.string(),
    excerpt: z.string(),
    startLine: z.number(),
    endLine: z.number(),
    version: z.string(),
    reason: z.string().optional(),
  }),
};
